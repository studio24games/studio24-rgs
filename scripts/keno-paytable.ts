// Generates the Keno paytable to a target RTP and prints it as TypeScript.
// Usage: node scripts/keno-paytable.ts 0.97 > src/games/keno-paytable.ts
//
// Rules: 40 numbers, 10 drawn, the player picks 1-10. Pays depend on picks and hits.
// Method: weight each paying hit count by (1/P(hits))^ALPHA, scale to the target RTP, round each multiplier
// DOWN to 0.01x, cap at MAX_MULT, then nudge the most likely paying line up by 0.01x steps while staying at or
// below the target. The exact RTP of the result is computed from the hypergeometric distribution.
import { hitProbabilities } from '../src/games/keno-maths.ts';

const target = Number(process.argv[2] ?? '0.97');
const ALPHA = Number(process.env.ALPHA ?? '0.6');
const MAX_MULT = 10_000_00; // 10,000x in hundredths
const minHit = (n: number) => Math.max(1, Math.ceil(n * 0.4));

const out: Record<number, number[]> = {};
for (let n = 1; n <= 10; n++) {
  const p = hitProbabilities(n);
  const pays = p.map((_, h) => (h >= minHit(n) ? Math.pow(1 / (p[h] as number), ALPHA) : 0));
  const scale = target / pays.reduce((s, w, h) => s + w * (p[h] as number), 0);
  let mult = pays.map(w => Math.min(MAX_MULT, Math.floor(w * scale * 100)));
  const rtp = (m: number[]) => m.reduce((s, x, h) => s + (x / 100) * (p[h] as number), 0);
  // The cap removes RTP from the top line; give it back to the lines below, most likely first.
  const order = mult.map((_, h) => h).filter(h => (mult[h] as number) > 0).sort((a, b) => (p[b] as number) - (p[a] as number));
  for (let guard = 0; guard < 1_000_000; guard++) {
    let moved = false;
    for (const h of order) {
      if ((mult[h] as number) >= MAX_MULT) continue;
      const trial = mult.slice(); trial[h] = (trial[h] as number) + 1;
      if (rtp(trial) <= target) { mult = trial; moved = true; break; }
    }
    if (!moved) break;
  }
  const paying = mult.filter(x => x > 0);
  if (paying.some((x, i) => i > 0 && x <= (paying[i - 1] as number))) throw new Error(`picks ${n}: pays must rise with hits: ${mult.join(',')}`);
  out[n] = mult;
}

const lines = Object.entries(out).map(([n, m]) => `  ${n}: [${m.join(', ')}],`).join('\n');
process.stdout.write(`// GENERATED by scripts/keno-paytable.ts with target RTP ${target}. Do not edit by hand.
// KENO_PAYTABLE[picks][hits] = multiplier in hundredths (385 = 3.85x). Index 0 = no hits.
export const KENO_TARGET_RTP = ${target};
export const KENO_PAYTABLE: Record<number, readonly number[]> = {
${lines}
};
`);
